import { describe, expect, it } from "vitest";
import { isReadOnlyShellCommand } from "../../src/domain/read-only-shell.js";

describe("read-only shell diagnostics", () => {
  it.each([
    "ls -la '/mnt/d/code/创业/简易计数器' 2>&1 | head -50; echo '---'; find '/mnt/d/code/创业/简易计数器' -maxdepth 2 -not -path '*/node_modules/*' 2>/dev/null | head -50",
    "cd '/mnt/d/code/创业/Agent-Harness' && grep -rn 'required_contract_missing\\|verification_command_missing' src/ --include=*.ts | head -20",
    "pwd; rg -n 'error|warning; info' src/ | head -n 20",
    "cat 'a file.txt' | wc -l\nstat README.md",
    "find . -type f -name '*.ts' -print | tail -5",
    "git status --short && git diff --stat",
    "git diff --no-ext-diff --no-textconv | head -20",
    "git show --no-ext-diff --no-textconv HEAD | head -20",
    "echo '---'; ls -la 2> /dev/null;",
    "grep -n -- 'rm -rf; $(literal)' README.md",
    "find . -name '*.ts'",
    'find . -name "*.ts"',
    "find . -name \\*.ts",
    "git diff --no-ext-diff --no-textconv -- '*.ts'",
    "grep -n pattern src/ --include=*.ts",
    "rg --glob=*.ts pattern src/",
  ])("accepts all read-only segments: %s", (command) => {
    expect(isReadOnlyShellCommand(command)).toBe(true);
  });

  it.each([
    "ls | head; rm -rf src",
    "cd . && touch src/new.ts",
    "pwd || node -e 'require(\"fs\").writeFileSync(\"a\", \"b\")'",
    "ls | tee src/list.txt",
    "ls > src/list.txt",
    "echo 'x' >> README.md",
    "ls 2> errors.txt",
    "cat README.md > /tmp/output.txt",
    "ls 2>&1 > src/output.txt",
    "find . -exec rm {} \\;",
    "find . -delete",
    "find . -fprint output.txt",
    "find . -okdir sh {} \\;",
    "rg --pre 'touch src/new.ts' pattern src",
    "git diff --output=src/diff.txt",
    "git diff --ext-diff",
    "git diff | head -20",
    "git diff --stat --patch",
    "git log -p | head -20",
    "git log -U3 | head -20",
    "git log --unified=3 | head -20",
    "git log -W | head -20",
    "git show HEAD | head -20",
    "git show --textconv HEAD:README.md",
    "git -c core.pager='touch a' log",
    "echo $(touch src/a)",
    "echo `touch src/a`",
    "ls \"$(touch src/a)\"",
    "ls <(touch src/a)",
    "ls & touch src/a",
    "ls &&",
    "| ls",
    "ls ||| pwd",
    "ls 'unterminated",
    "ls # comment\ntouch src/a",
    "bash -c 'ls'",
    "node scripts/read.mjs",
    "npm test",
    "find . *",
    "find . ?delete",
    "find . [-]delete",
    "find . -name *.ts",
    "git diff *",
    "git diff -- *",
    "git show ?*",
    "rg * pattern src",
    "rg --pre=* pattern src",
    "grep --inc*=*.ts pattern src",
    "",
  ])("does not exempt unsafe or unsupported shell syntax: %s", (command) => {
    expect(isReadOnlyShellCommand(command)).toBe(false);
  });
});
